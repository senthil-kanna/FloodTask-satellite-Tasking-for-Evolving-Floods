"""Regenerate all tables, statistics and figures from raw episode files (results/experiments/*/episodes.jsonl).

  python scripts/analyze.py
Outputs: results/analysis/*.csv|json, results/figures/*.png, results/analysis/summary.md
"""
from __future__ import annotations

import json

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from floodtask.eval.stats import compare, holm, mixed_effects  # noqa: E402
from floodtask.utils import load_json, load_yaml, RESULTS, ROOT, save_json  # noqa: E402

EXP, OUT, FIG = RESULTS / "experiments", RESULTS / "analysis", RESULTS / "figures"
THRESH = 0.5
MAIN = "ppo_recurrent"
NAMES = {"random": "Random", "stalest": "Longest-unobserved", "flooded_first": "Flooded-first",
         "forecast": "Forecast-following", "greedy_unc": "Greedy uncertainty (tuned)", "oracle": "Oracle (non-operational)",
         "ppo_recurrent": "Recurrent PPO (forecast-aware)", "ppo_feedforward": "Feed-forward PPO",
         "ppo_recurrent_noforecast": "Recurrent PPO, no forecast", "ppo_recurrent_unc": "Recurrent PPO + uncertainty bonus",
         "ppo_recurrent_iou": "Recurrent PPO, IoU reward"}


def event_of(scene):
    return scene.rsplit("_", 1)[0]


def load(tag) -> pd.DataFrame:
    rows = []
    with open(EXP / tag / "episodes.jsonl") as f:
        for line in f:
            e = json.loads(line)
            fp_ = [p.get("flood_present", True) for p in e["passes"]]
            ious = [p["iou"] if f else np.nan for p, f in zip(e["passes"], fp_)]   # IoU only where flood present
            if not any(fp_):
                continue   # episode never floods: excluded from IoU endpoints (counted in meta)
            reach = [i for i, v in enumerate(ious) if v >= THRESH]
            last = e["passes"][-1]
            rows.append({"policy": e["policy"], "train_seed": e.get("train_seed", -1), "scene": e["scene"],
                         "event": event_of(e["scene"]), "episode_seed": e["seed"], "forecast_mode": e.get("forecast_mode"),
                         "mean_iou": float(np.nanmean(ious)), "final_iou": ious[-1],
                         "false_alarm_frac": float(np.mean([p.get("false_alarm_frac", np.nan) for p in e["passes"]])), "final_f1": last["f1"], "final_precision": last["precision"],
                         "final_recall": last["recall"], "final_area_bias": last["area_bias"],
                         "final_pixel_error": last["pixel_error"], "final_boundary_f1": last["boundary_f1"],
                         "time_to_thresh": (reach[0] + 1) if reach else len(ious) + 1, "reached": bool(reach),
                         "return": e["return"], "latency_ms": e["decision_latency_ms_mean"],
                         "true_flood_frac_mid": e["passes"][len(e["passes"]) // 2]["true_flood_frac"],
                         **{f"iou_p{i}": v for i, v in enumerate(ious)},
                         "unique_tiles": last.get("unique_tiles"),
                         "flooded_tiles_seen_frac": (last.get("unique_flooded_tiles_seen", np.nan) / max(last.get("flooded_tiles", 1), 1))
                         if "flooded_tiles" in last else np.nan})
    return pd.DataFrame(rows)


def table(df, metrics=("mean_iou", "final_iou", "final_f1", "final_precision", "final_recall", "final_area_bias",
                       "final_boundary_f1", "time_to_thresh", "reached", "false_alarm_frac", "latency_ms")):
    g = df.groupby(["policy", "train_seed", "scene", "episode_seed"], as_index=False)[list(metrics)].mean()
    g = g.groupby(["policy", "scene", "episode_seed"], as_index=False)[list(metrics)].mean()   # average seeds
    t = g.groupby("policy")[list(metrics)].agg(["mean", "std"])
    t.columns = [f"{a}_{b}" for a, b in t.columns]
    t["n_episodes"] = g.groupby("policy").size()
    return t.sort_values("mean_iou_mean", ascending=False)


def curves(df, ax, title):
    cols = [c for c in df.columns if c.startswith("iou_p")]
    for pol, g in df.groupby("policy"):
        m = g.groupby(["scene", "episode_seed"])[cols].mean().mean(skipna=True)
        ax.plot(range(1, len(cols) + 1), m.values, marker="o" if pol.startswith("ppo") else None,
                ls="--" if pol == "oracle" else "-", label=NAMES.get(pol, pol), lw=2 if pol == MAIN else 1)
    ax.set_xlabel("Pass"); ax.set_ylabel("IoU"); ax.set_title(title); ax.grid(alpha=0.3)


def main():
    OUT.mkdir(parents=True, exist_ok=True); FIG.mkdir(parents=True, exist_ok=True)
    tags = sorted(p.name for p in EXP.iterdir() if (p / "episodes.jsonl").exists())
    data = {t: load(t) for t in tags}
    summary = ["# Results summary (auto-generated by scripts/analyze.py)\n"]
    primary = load_yaml(ROOT / "configs" / "data.yaml")["primary_test_event"]

    if "core" in data:
        core = data["core"]
        if "ablation" in data:
            core_all = pd.concat([core, data["ablation"]])
        else:
            core_all = core
        for scope, df in (("all_test_events", core_all), (primary, core_all[core_all.event == primary])):
            t = table(df)
            t.to_csv(OUT / f"core_table_{scope}.csv")
            summary += [f"## Core comparison - {scope}\n", t[["mean_iou_mean", "mean_iou_std", "final_iou_mean", "final_f1_mean",
                        "final_area_bias_mean", "time_to_thresh_mean", "reached_mean", "n_episodes"]].round(4).to_markdown(), "\n"]
            fam = [c for c in ["random", "stalest", "flooded_first", "forecast", "greedy_unc", "ppo_feedforward",
                               "ppo_recurrent_noforecast"] if c in set(df.policy)]
            res = holm([compare(df, "mean_iou", MAIN, b) for b in fam])
            sec = [compare(df, m, MAIN, b) for m in ("final_iou", "time_to_thresh", "final_area_bias")
                   for b in fam]
            mixed = [mixed_effects(df, "mean_iou", MAIN, b) for b in fam]
            save_json({"confirmatory": res, "secondary": sec, "mixed_effects_crosscheck": mixed}, OUT / f"stats_core_{scope}.json")
            summary.append(f"### Paired comparisons, primary endpoint (mean per-pass IoU), {MAIN} minus comparator, {scope}\n")
            summary.append("| comparator | diff | 95% CI | Wilcoxon p | Holm p | d_z | seeds>0 | scenes | per-event |\n|---|---|---|---|---|---|---|---|---|")
            for r in res:
                pe = ", ".join(f"{k}: {v:+.3f}" for k, v in r["per_event_mean_diff"].items())
                summary.append(f"| {r['b']} | {r['mean_diff']:+.4f} | [{r['ci95'][0]:+.4f}, {r['ci95'][1]:+.4f}] | "
                               f"{r['wilcoxon_p']:.2g} | {r['p_holm']:.2g} | {r['cohen_dz']:.2f} | "
                               f"{r['n_seeds_positive']}/{len(r['per_seed_mean_diff'])} | {r['n_scenes']} | {pe} |")
            summary.append("\nMixed-effects cross-check (episode-level, random intercept per scene):\n")
            for m in mixed:
                summary.append(f"- vs {m['b']}: " + (f"{m['intercept']:+.4f} [{m['ci95'][0]:+.4f}, {m['ci95'][1]:+.4f}], p={m['p']:.2g}"
                                                    if "error" not in m else f"fit failed: {m['error']}"))
            summary.append("")
            fig, ax = plt.subplots(figsize=(8, 5))
            curves(df, ax, f"Per-pass IoU, test scenes ({scope})")
            ax.legend(fontsize=7); fig.tight_layout(); fig.savefig(FIG / f"per_pass_iou_{scope}.png", dpi=150); plt.close(fig)
        # reward validity: return vs mean IoU (RL main policy)
        r = core[core.policy == MAIN]
        if len(r):
            rho = float(pd.Series(r["return"]).corr(r["mean_iou"], method="spearman"))
            summary.append(f"Reward validity (test, {MAIN}): Spearman rho(return, mean IoU) = {rho:.3f}\n")
        # flood-size strata
        q = core.true_flood_frac_mid.quantile([1 / 3, 2 / 3]).values
        core["size_stratum"] = np.digitize(core.true_flood_frac_mid, q)
        st = core.groupby(["size_stratum", "policy"]).mean_iou.mean().unstack(0)
        st.columns = ["small", "medium", "large"][:len(st.columns)]
        st.to_csv(OUT / "flood_size_strata.csv")
        summary += ["## Flood-size strata (tertiles of mid-episode flooded fraction)\n", st.round(4).to_markdown(), "\n"]

    # robustness / generalisation suites: mean per-pass IoU per policy per condition
    cond = {t: d for t, d in data.items() if t.startswith(("forecast_", "sensor_", "budget_", "revisit_", "latency_"))}
    if cond:
        rows = {}
        for t, d in cond.items():
            rows[t] = d.groupby(["policy", "scene", "episode_seed"]).mean_iou.mean().groupby("policy").mean()
        if "core" in data:
            rows["core (operational, K=16, 12h, L=0)"] = data["core"].groupby(["policy", "scene", "episode_seed"]).mean_iou.mean().groupby("policy").mean()
        R = pd.DataFrame(rows).T
        R.to_csv(OUT / "conditions_mean_iou.csv")
        summary += ["## Robustness and generalisation conditions (mean per-pass IoU, all test scenes)\n", R.round(4).to_markdown(), "\n"]
        stats_c = {}
        for t, d in cond.items():
            if MAIN in set(d.policy):
                stats_c[t] = [compare(d, "mean_iou", MAIN, b) for b in ("greedy_unc", "stalest", "ppo_feedforward") if b in set(d.policy)]
        save_json(stats_c, OUT / "stats_conditions.json")
        fmodes = [t for t in R.index if t.startswith("forecast_")]
        if fmodes and "core (operational, K=16, 12h, L=0)" in R.index:
            fig, ax = plt.subplots(figsize=(9, 4.5))
            base = R.loc["core (operational, K=16, 12h, L=0)"]
            sub = R.loc[fmodes].sub(base)
            sub = sub[[c for c in sub.columns if c != "oracle"]]
            sub.plot.bar(ax=ax)
            ax.axhline(0, color="k", lw=0.8); ax.set_ylabel("Change in mean per-pass IoU vs operational")
            ax.set_title("Forecast-corruption robustness (test scenes)"); ax.legend(fontsize=6)
            fig.tight_layout(); fig.savefig(FIG / "forecast_robustness.png", dpi=150); plt.close(fig)
        bud = [t for t in ["budget_8"] if t in R.index] + (["core (operational, K=16, 12h, L=0)"] if "core" in data else []) + \
              [t for t in ["budget_32"] if t in R.index]
        if len(bud) == 3:
            fig, ax = plt.subplots(figsize=(6, 4.5))
            for pol in R.columns:
                ax.plot([8, 16, 32], R.loc[bud, pol].values, marker="o", label=NAMES.get(pol, pol))
            ax.set_xscale("log", base=2); ax.set_xlabel("Tiles per pass"); ax.set_ylabel("Mean per-pass IoU")
            ax.set_title("Accuracy vs imaging budget"); ax.legend(fontsize=6); ax.grid(alpha=0.3)
            fig.tight_layout(); fig.savefig(FIG / "budget_curve.png", dpi=150); plt.close(fig)

    for t in [t for t in data if t.startswith("real_")]:
        d = data[t]
        meta = load_json(EXP / t / "meta.json")
        summary.append(f"## Real-event replay: {t} ({len(set(d.scene))} scenes)\n")
        summary.append(f"Forecast note: {meta['forecast_note']}\n")
        if meta.get("label_check"):
            lc = meta["label_check"]
            summary.append(f"Hand-label check on {lc['label_date']} ({lc['n_labelled_cells_60m']} labelled 60 m cells): "
                           f"reference IoU {lc['reference']['iou']:.3f}, deployed U-Net IoU {lc['unet_obs']['iou']:.3f}\n")
        tab = d.groupby(["forecast_mode", "policy"]).agg(mean_iou=("mean_iou", "mean"), final_iou=("final_iou", "mean"),
                                         time_to_thresh=("time_to_thresh", "mean"), n=("mean_iou", "size"))
        summary += [tab.round(4).to_markdown(), "\n"]
        fig, axs = plt.subplots(1, 2, figsize=(13, 5), sharey=True)
        for ax, mode in zip(axs, ("operational", "missing")):
            curves(d[d.forecast_mode == mode], ax, f"{t}: forecast {mode}")
        axs[0].legend(fontsize=7); fig.tight_layout(); fig.savefig(FIG / f"{t}_per_pass_iou.png", dpi=150); plt.close(fig)

    (OUT / "summary.md").write_text("\n".join(summary), encoding="utf-8")
    print("\n".join(summary))


if __name__ == "__main__":
    main()
